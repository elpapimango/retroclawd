#!/usr/bin/env python3
"""Converts RetroArch's gamepad autoconfig profiles (the `autoconfig/<driver>/*.cfg` files of a RetroArch install, or of
https://github.com/libretro/retroarch-joypad-autoconfig) into `assets/controllers/devices.toml`, the list of controllers
retroclawd knows by name.

    python tools/convert_autoconfig.py "C:/path/to/RetroArch-Win64/autoconfig" [assets/controllers/devices.toml]

One `[[device]]` per USB vendor/product pair (`vid`, `pid` as 4-digit hex, the way a device manager shows them) with the
name RetroArch gives it. A pair several profiles describe (one per driver) takes the name of the most common driver on
the platform first (xinput, sdl2, dinput, hid, ...). The output is sorted, so a run changes the file only where
RetroArch's data changed. The button numbers of the profiles are not carried over: the program reads pads through the
operating system's standard gamepad layer, which already says which button is which (see assets/controllers/layouts.toml
for what each one does on each machine).
"""
import re
import sys
from pathlib import Path

# The drivers whose profiles name a device best come first; the rest are the order of the alphabet.
DRIVER_ORDER = ["xinput", "sdl2", "dinput", "hid", "winraw", "udev", "linuxraw", "android", "qnx", "mfi", "parport", "x"]
LINE = re.compile(r'^\s*([A-Za-z0-9_]+)\s*=\s*"?([^"#]*?)"?\s*(?:#.*)?$')


def read_cfg(path):
    values = {}
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = LINE.match(raw)
        if m and not raw.lstrip().startswith("#"):
            values[m.group(1)] = m.group(2).strip()
    return values


def toml_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    root = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "assets/controllers/devices.toml"
    if not root.is_dir():
        sys.exit(f"{root} is not a folder")
    drivers = sorted((d for d in root.iterdir() if d.is_dir()), key=lambda d: (DRIVER_ORDER.index(d.name) if d.name in DRIVER_ORDER else len(DRIVER_ORDER), d.name))
    devices = {}
    for driver in drivers:
        for cfg in sorted(driver.glob("*.cfg")):
            values = read_cfg(cfg)
            try:
                vid = int(values["input_vendor_id"])
                pid = int(values["input_product_id"])
            except (KeyError, ValueError):
                continue  # profiles without a usable id cannot be matched
            if not (0 < vid < 0x10000 and 0 <= pid < 0x10000):
                continue
            name = values.get("input_device_display_name") or values.get("input_device") or cfg.stem
            devices.setdefault((vid, pid), name.strip())
    lines = [
        "# Generated by tools/convert_autoconfig.py from RetroArch's gamepad autoconfig profiles: do not edit by hand.",
        "# The controllers the program knows by name (USB vendor and product id, 4 hex digits).",
        "",
    ]
    for (vid, pid), name in sorted(devices.items()):
        lines += ["[[device]]", f'vid = "{vid:04x}"', f'pid = "{pid:04x}"', f"name = {toml_string(name)}", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(devices)} controllers from {root} -> {out}")


if __name__ == "__main__":
    main()
